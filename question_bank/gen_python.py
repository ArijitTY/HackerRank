def main():
    rows = build_rows()

    # Sanity checks before writing
    assert len(rows) == 500, f"Expected 500 rows, got {len(rows)}"

    # Check question uniqueness (question + code_snippet combo for output/code_completion)
    question_keys = [(r["question"] + "|" + r["code_snippet"]) for r in rows]
    assert len(set(question_keys)) == 500, f"Duplicate questions detected! {500 - len(set(question_keys))} duplicates"

    # Check "all of the above" <= 5%
    aota_count = sum(
        1 for r in rows
        if any("all of the above" in opt.lower()
               for opt in [r["option_a"], r["option_b"], r["option_c"], r["option_d"]])
    )
    assert aota_count <= 25, f"Too many 'all of the above' options: {aota_count}"

    # Check output questions have code_snippet
    for r in rows:
        if r["type"] == "output":
            assert r["code_snippet"] != "", f"Output question {r['id']} missing code_snippet"
        if r["type"] == "code_completion":
            assert "___" in r["code_snippet"], f"Code completion question {r['id']} missing ___ in code_snippet"
        if r["type"] in ("mcq", "scenario"):
            assert r["code_snippet"] == "", f"{r['type']} question {r['id']} should have empty code_snippet"
        assert r["correct_answer"] in ("A", "B", "C", "D"), f"Invalid correct_answer in question {r['id']}"

    # Write CSV
    df = pd.DataFrame(rows)
    output_path = r"D:\HackerRankSimulation\question_bank\python_questions.csv"
    df.to_csv(output_path, index=False, quoting=csv.QUOTE_ALL)
    print(f"Wrote {len(df)} questions to {output_path}")

    # Verification
    df2 = pd.read_csv(output_path, keep_default_na=False)
    print(f"\nVerification: {len(df2)} rows loaded from CSV\n")

    print("=== Type Distribution ===")
    print(df2["type"].value_counts().to_string())

    print("\n=== Difficulty Distribution ===")
    print(df2["difficulty"].value_counts().to_string())

    print(f"\n=== Difficulty Percentages ===")
    for diff, count in df2["difficulty"].value_counts().items():
        print(f"  {diff}: {count} ({count/5:.1f}%)")

    print(f"\n=== Topic Coverage ===")
    print(df2["topic"].value_counts().to_string())

    print(f"\nAll correct_answers valid: {df2['correct_answer'].isin(['A','B','C','D']).all()}")
    print(f"Unique questions: {df2['question'].nunique()}")
    print(f"All subjects are 'Python': {(df2['subject'] == 'Python').all()}")


if __name__ == "__main__":
    main()

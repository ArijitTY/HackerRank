def build_questions():
    questions = []
    qid = 1

    # Shuffle templates and assign correct answers with randomized option order
    def make_row(template, qtype):
        nonlocal qid
        opts = template["options"][:]
        correct_text = opts[0]  # The first option is always the correct one in templates

        # Shuffle options
        random.shuffle(opts)
        correct_letter = chr(65 + opts.index(correct_text))  # A, B, C, or D

        code = template.get("code_snippet", "")

        row = {
            "id": qid,
            "subject": "SQL",
            "topic": template.get("topic", pick_topic()),
            "difficulty": template.get("difficulty", pick_difficulty()),
            "type": qtype,
            "question": template["question"],
            "option_a": opts[0],
            "option_b": opts[1],
            "option_c": opts[2],
            "option_d": opts[3],
            "correct_answer": correct_letter,
            "explanation": template["explanation"],
            "code_snippet": code,
        }
        qid += 1
        return row

    # --- MCQ: 200 questions ---
    mcq_templates = MCQ_TEMPLATES[:]
    # We have enough templates; pad if necessary
    while len(mcq_templates) < 200:
        # Duplicate with slight variation
        base = random.choice(MCQ_TEMPLATES)
        variant = base.copy()
        variant["question"] = base["question"].rstrip("?") + " in SQL?"
        mcq_templates.append(variant)
    random.shuffle(mcq_templates)
    for t in mcq_templates[:200]:
        questions.append(make_row(t, "mcq"))

    # --- OUTPUT: 100 questions ---
    out_templates = OUTPUT_TEMPLATES[:]
    while len(out_templates) < 100:
        base = random.choice(OUTPUT_TEMPLATES)
        variant = base.copy()
        variant["question"] = "Given the SQL below, what is the output?"
        out_templates.append(variant)
    random.shuffle(out_templates)
    for t in out_templates[:100]:
        questions.append(make_row(t, "output"))

    # --- SCENARIO: 100 questions ---
    scn_templates = SCENARIO_TEMPLATES[:]
    while len(scn_templates) < 100:
        base = random.choice(SCENARIO_TEMPLATES)
        variant = base.copy()
        variant["question"] = "Consider this scenario: " + base["question"]
        scn_templates.append(variant)
    random.shuffle(scn_templates)
    for t in scn_templates[:100]:
        questions.append(make_row(t, "scenario"))

    # --- CODE COMPLETION: 100 questions ---
    cc_templates = CODE_COMPLETION_TEMPLATES[:]
    while len(cc_templates) < 100:
        base = random.choice(CODE_COMPLETION_TEMPLATES)
        variant = base.copy()
        variant["question"] = "Fill in the blank: " + base["question"]
        cc_templates.append(variant)
    random.shuffle(cc_templates)
    for t in cc_templates[:100]:
        questions.append(make_row(t, "code_completion"))

    return questions


def main():
    questions = build_questions()

    df = pd.DataFrame(questions)

    # Ensure correct column order
    cols = [
        "id", "subject", "topic", "difficulty", "type",
        "question", "option_a", "option_b", "option_c", "option_d",
        "correct_answer", "explanation", "code_snippet",
    ]
    df = df[cols]

    output_path = r"D:\HackerRankSimulation\question_bank\sql_questions.csv"
    df.to_csv(output_path, index=False, quoting=csv.QUOTE_ALL)

    print(f"Row count: {len(df)}")


if __name__ == "__main__":
    main()
